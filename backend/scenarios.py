# ── Pydantic Schemas for Structured AI Test Plans ─────────────────────────────

class PlanAction(BaseModel):
    """An individual bounded browser action proposed in a test plan."""
    step: int = Field(..., description="Step sequence number starting at 1")
    action_type: str = Field(
        ...,
        description="One of: navigate, locate_and_fill, type, fill, click, wait_for_route, assert_element_count, assert_error_message, capture_screenshot"
    )
    target: str = Field(..., description="Approved element alias, URL, route path, or assertion parameter")
    description: str = Field(..., description="Human-readable description of what this step accomplishes")
    value: Optional[str] = Field(default=None, description="Optional parameter or input text for fill/type actions")


class TestPlan(BaseModel):
    """The complete structured test plan returned by the AI planner."""
    plan_id: str = Field(..., description="Unique plan identifier, e.g. plan_abc123")
    goal: str = Field(..., description="The user's original natural-language testing intent")
    interpreted_goal: str = Field(..., description="Refined, standardized testing goal formulated by the planner")
    scenario_id: Optional[str] = Field(
        default=None,
        description="One of: smoke_test, saucedemo_valid_login, saucedemo_locked_out_login, saucedemo_invalid_login, or None if unsupported"
    )
    target_origin: str = Field(..., description="Expected origin for this test, e.g. https://www.saucedemo.com/")
    actions: List[PlanAction] = Field(default_factory=list, description="Ordered list of permitted browser actions")
    expected_outcomes: List[str] = Field(default_factory=list, description="Assertions that will verify the test outcome")
    explanation: str = Field(..., description="Explanation of why this plan satisfies the user's goal")
    is_supported: bool = Field(default=True, description="Whether the user goal maps to an approved scenario")
    unsupported_reason: Optional[str] = Field(default=None, description="Explanation if the requested goal is unsupported")
    provider: str = Field(default="deterministic_fallback", description="Planner provider: 'gemini' or 'deterministic_fallback'")
    model: Optional[str] = Field(default=None, description="Model identifier if generated by an LLM")
